-- 1. ESTRUTURA DE PERFIS E MULTI-TENANCY
CREATE TABLE public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    email TEXT,
    nome TEXT, 
    tipo TEXT NOT NULL DEFAULT 'membro',
    foto TEXT, 
    family_id UUID NOT NULL DEFAULT gen_random_uuid(), 
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE public.convites (
    id SERIAL PRIMARY KEY,
    family_id UUID NOT NULL,
    email TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. FUNÇÕES DE APOIO
CREATE OR REPLACE FUNCTION public.get_my_family_id()
RETURNS UUID AS $$
BEGIN
    RETURN (SELECT family_id FROM public.profiles WHERE id = auth.uid());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 3. GATILHO PARA NOVOS USUÁRIOS
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
DECLARE
  target_family_id UUID;
BEGIN
  SELECT family_id INTO target_family_id FROM public.convites WHERE email = new.email;
  IF target_family_id IS NOT NULL THEN
    INSERT INTO public.profiles (id, email, family_id, nome, foto, tipo)
    VALUES (new.id, new.email, target_family_id, 
      COALESCE(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
      new.raw_user_meta_data->>'avatar_url', 'membro');
    DELETE FROM public.convites WHERE email = new.email;
  ELSE
    INSERT INTO public.profiles (id, email, family_id, nome, foto, tipo)
    VALUES (new.id, new.email, gen_random_uuid(), 
      COALESCE(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
      new.raw_user_meta_data->>'avatar_url', 'titular');
  END IF;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 4. TABELAS DE NEGÓCIO (TITULARES E CONFIGURAÇÕES)
CREATE TABLE public.titulares (
    id SERIAL PRIMARY KEY,
    family_id UUID NOT NULL DEFAULT public.get_my_family_id(),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    nome TEXT NOT NULL,
    foto TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE(family_id, nome)
);

CREATE TABLE public.cartoes_config (
    id SERIAL PRIMARY KEY,
    family_id UUID NOT NULL DEFAULT public.get_my_family_id(),
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    nome_cartao TEXT NOT NULL,
    titular_id INTEGER REFERENCES public.titulares(id) ON DELETE CASCADE,
    dia_vencimento INTEGER NOT NULL CHECK (dia_vencimento BETWEEN 1 AND 31),
    dia_fechamento INTEGER NOT NULL DEFAULT 7,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 5. MÓDULO DE EMPRÉSTIMOS E FINANCIAMENTOS
CREATE TABLE public.emprestimos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) NOT NULL,
  family_id UUID NOT NULL DEFAULT public.get_my_family_id(), 
  descricao TEXT NOT NULL,
  valor_total NUMERIC(15, 2),
  valor_parcela NUMERIC(15, 2) NOT NULL,
  taxa_mensal_percentual NUMERIC(10, 4) NOT NULL, 
  taxa_anual_percentual NUMERIC(10, 4),
  total_parcelas INT NOT NULL,
  parcela_atual INT DEFAULT 1,
  data_primeiro_vencimento DATE NOT NULL,
  competencia_inicial TEXT,
  titular_id INTEGER REFERENCES public.titulares(id) ON DELETE SET NULL,
  saldo_devedor_atual NUMERIC(15, 2),
  valor_amortizacao_base NUMERIC(15, 2),
  indexador_mensal_estimado NUMERIC(10, 4) DEFAULT 0,
  seguros_taxas NUMERIC(15, 2) DEFAULT 0,
  valor_subsidio_fgts NUMERIC(15, 2) DEFAULT 0,
  meses_subsidio_restantes INT DEFAULT 0,
  fgts_mes_inicio TEXT,
  fgts_percentual_utilizado NUMERIC(10, 4),
  fgts_valor_total NUMERIC(15, 2),
  categoria TEXT CHECK (categoria IN ('Veículo', 'Imóvel')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. MÓDULO DE CONTAS FIXAS (VIRTUAIS)
CREATE TABLE public.contas_fixas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) NOT NULL,
    family_id UUID NOT NULL DEFAULT public.get_my_family_id(),
    descricao TEXT NOT NULL,
    valor_mensal NUMERIC(15, 2) NOT NULL,
    total_parcelas INTEGER, -- NULL indica sem prazo (indeterminado)
    parcela_atual INTEGER NOT NULL DEFAULT 1,
    data_inicio DATE NOT NULL,
    competencia_inicial TEXT NOT NULL,
    titular_id INTEGER REFERENCES public.titulares(id) ON DELETE SET NULL,
    categoria TEXT,
    tipo TEXT NOT NULL DEFAULT 'despesa' CHECK (tipo IN ('despesa', 'receita')),
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

