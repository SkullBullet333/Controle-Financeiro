-- Políticas de Acesso
DO $$ 
DECLARE 
    tab TEXT;
BEGIN
    FOR tab IN SELECT table_name FROM information_schema.tables 
               WHERE table_schema = 'public' AND table_name IN ('titulares', 'cartoes_config', 'cartoes', 'despesas', 'receitas', 'table_notas', 'emprestimos', 'convites', 'contas_fixas')
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Acesso por Família" ON public.%I', tab);
        EXECUTE format('CREATE POLICY "Acesso por Família" ON public.%I FOR ALL USING (family_id = get_my_family_id()) WITH CHECK (family_id = get_my_family_id())', tab);
    END LOOP;
END $$;

CREATE POLICY "Leitura de perfis da família" ON public.profiles FOR SELECT USING (id = auth.uid() OR family_id = public.get_my_family_id());
CREATE POLICY "Permitir inserção do próprio perfil" ON public.profiles FOR INSERT WITH CHECK (id = auth.uid());
CREATE POLICY "Atualização do próprio perfil" ON public.profiles FOR UPDATE USING (id = auth.uid());
CREATE POLICY "Exclusão do próprio perfil" ON public.profiles FOR DELETE USING (id = auth.uid());

-- 9. GATILHOS E UTILITÁRIOS
CREATE OR REPLACE FUNCTION public.handle_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ language 'plpgsql';

CREATE TRIGGER tr_despesas_updated_at BEFORE UPDATE ON public.despesas FOR EACH ROW EXECUTE PROCEDURE public.handle_updated_at();
CREATE TRIGGER tr_receitas_updated_at BEFORE UPDATE ON public.receitas FOR EACH ROW EXECUTE PROCEDURE public.handle_updated_at();
CREATE TRIGGER tr_notas_updated_at BEFORE UPDATE ON public.table_notas FOR EACH ROW EXECUTE PROCEDURE public.handle_updated_at();
CREATE TRIGGER tr_contas_fixas_updated_at BEFORE UPDATE ON public.contas_fixas FOR EACH ROW EXECUTE PROCEDURE public.handle_updated_at();

